#!/usr/bin/env bash
# Out-of-band advisory check for the vendored (`[patch.crates-io]`) crates.
#
# Why this exists
# ---------------
# The workspace vendors `rustls`, `yamux` and `russh` through
# `[patch.crates-io]`. A patched (path) crate has no registry source, and both
# `cargo-deny` and `cargo-audit` drop a package with no crates.io source before
# the advisory lookup, so a vulnerability in one of those versions is invisible
# to `cargo deny check` / `cargo audit` on the patched tree. (See the backlog
# item "Vendored crates are invisible to the *advisory* checks".)
#
# This script re-derives the verdict the patched tree cannot give: it reads the
# version currently pinned in each `vendor/*/Cargo.toml`, synthesises a lockfile
# that names only those crates at their crates.io source, and audits *that*
# lockfile. Versions are read at run time, never hard-coded, so the check
# re-runs on its own after a vendor bump.
#
# It fails closed: a missing `cargo-audit`, an unreadable vendored manifest, or
# any matching advisory (a vulnerability, or an informational
# unmaintained/unsound/notice warning) makes it exit 1.
#
# Usage:
#   bash scripts/vendored-advisory-check.sh [--no-fetch] [--quiet]
#     --no-fetch  pass `--no-fetch` to cargo-audit (offline; uses the local
#                 advisory DB, which may be stale — the CI step does not pass
#                 this, so it fetches the current DB)
#     --quiet     suppress the per-crate listing
#
# The CI home is the `security` job (`.github/workflows/ci.yml`); it can also be
# run by hand before a release. Recorded in `docs/developing.md`
# § Pre-release checklist, "Vendored crates".

set -u

self_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repo_root=$(cd -- "$self_dir/.." && pwd)
cd "$repo_root" || { printf 'FAIL cannot cd to %s\n' "$repo_root" >&2; exit 1; }

no_fetch=0
quiet=0
for arg in "$@"; do
    case "$arg" in
        --no-fetch) no_fetch=1 ;;
        --quiet) quiet=1 ;;
        *) printf 'usage: %s [--no-fetch] [--quiet]\n' "${BASH_SOURCE[0]}" >&2; exit 2 ;;
    esac
done

command -v cargo-audit >/dev/null 2>&1 || {
    printf 'FAIL cargo-audit is not on PATH — the vendored advisory check cannot run\n' >&2
    exit 1
}
command -v awk >/dev/null 2>&1 || {
    printf 'FAIL awk is not on PATH — cannot read vendor manifests\n' >&2
    exit 1
}

# --- read the pinned versions ------------------------------------------------
# Parse only the `[package]` table: several vendor manifests carry `[[test]]` /
# `[[example]]` / `[[bin]]` tables whose own `name`/`version` keys must not be
# mistaken for the crate's.
pkg_field() { # <manifest> <field>
    awk -v want="$2" '
        /^\[package\]/ { p = 1; next }
        /^\[/ { p = 0 }
        p {
            key = $0
            sub(/[ \t]*=.*$/, "", key)
            if (key == want) {
                val = $0
                sub(/^[^=]*=[ \t]*/, "", val)
                gsub(/"/, "", val)
                sub(/[ \t]*#.*$/, "", val)
                sub(/[ \t]+$/, "", val)
                print val
                exit
            }
        }
    ' "$1"
}

entries=''
count=0
for man in vendor/*/Cargo.toml; do
    [ -e "$man" ] || [ -L "$man" ] || continue
    name=$(pkg_field "$man" name)
    ver=$(pkg_field "$man" version)
    if [ -z "$name" ] || [ -z "$ver" ]; then
        printf 'FAIL %s: could not read [package] name/version — the vendor tree is malformed or the parser is stale\n' "$man" >&2
        exit 1
    fi
    entries="${entries}${name} ${ver}"$'\n'
    count=$((count + 1))
done

if [ "$count" -eq 0 ]; then
    printf 'FAIL no vendored crate manifest found under vendor/*/Cargo.toml\n' >&2
    exit 1
fi

# --- synthesise the out-of-band lockfile -------------------------------------
# No checksum is needed: cargo-audit matches advisories by (name, version) and
# only needs the crates.io `source` to treat the package as registry-resolved.
tmp=$(mktemp -d "${TMPDIR:-/tmp}/frp-vendored-audit.XXXXXX") || {
    printf 'FAIL mktemp -d failed\n' >&2
    exit 1
}
trap 'rm -rf "$tmp"' EXIT
lock="$tmp/Cargo.lock"

{
    printf '# Synthetic lockfile — names ONLY the vendored crates, at their\n'
    printf '# crates.io source, so the advisory lookup runs out of band of the\n'
    printf '# patched tree. Generated by scripts/vendored-advisory-check.sh.\n'
    printf 'version = 3\n\n'
    printf '%s' "$entries" | while IFS=' ' read -r name ver; do
        [ -n "$name" ] || continue
        printf '[[package]]\nname = "%s"\nversion = "%s"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n\n' "$name" "$ver"
    done
} > "$lock" || {
    printf 'FAIL could not write the synthetic lockfile\n' >&2
    exit 1
}

# The lock must carry exactly the crates read above; a short write would let the
# audit pass on a subset.
got=$(grep -c '^\[\[package\]\]$' "$lock" || true)
if [ "$got" != "$count" ]; then
    printf 'FAIL synthetic lockfile lists %s package(s), expected %s\n' "$got" "$count" >&2
    exit 1
fi

if [ "$quiet" != 1 ]; then
    printf 'vendored crates checked out of band (crates.io source):\n'
    printf '%s' "$entries" | while IFS=' ' read -r name ver; do
        [ -n "$name" ] || continue
        printf '  %-8s %s\n' "$name" "$ver"
    done
fi

# --- audit -------------------------------------------------------------------
# --no-yanked: the question is advisories, and the yank check needs registry
# index metadata the synthetic lock deliberately does not fetch.
args=(--no-yanked --file "$lock" -D warnings)
[ "$no_fetch" = 1 ] && args+=(--no-fetch)

if ! cargo audit "${args[@]}"; then
    printf '\nFAIL the vendored advisory check found an advisory for a currently pinned version.\n' >&2
    printf '      Review https://rustsec.org/ and re-vendor or bump the affected crate; a green\n' >&2
    printf '      `cargo deny check` / `cargo audit` on the patched tree does NOT cover this.\n' >&2
    exit 1
fi

printf 'vendored advisory check ok: %s crate(s) pinned in vendor/*/Cargo.toml have no matching advisory\n' "$count"
