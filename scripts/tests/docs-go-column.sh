def expected_failure(exp, cell, tok):
    """None when `cell` is the recorded cell for `exp`; else why it is not."""
    if exp.startswith('go:'):
        want = exp[3:]
        if want not in GO:
            return 'its recorded Go path `%s` is not in the key set' % want
        if cell != '`%s`' % want:
            return 'expected the recorded Go path `%s`, found %s' % (want, short(cell))
        return None
    if exp.startswith('qualified:'):
        want, shape = exp[len('qualified:'):].split(':')
        q = QUAL.match(cell)
        if want not in GO:
            return 'its recorded Go path `%s` is not in the key set' % want
        if q is None or q.group(1) != want or q.group(2) != shape:
            return 'expected the recorded Go path `%s` (%s), found %s' % (want, shape, short(cell))
        return None
    if exp.startswith('extension:'):
        spelling = exp[len('extension:'):]
        if spelling in GO:
            return 'the recorded extension spelling `%s` is a Go v0.71.0 key' % spelling
        if not DIVERGENT.match(cell):
            return 'expected a divergence marker naming `%s`, found %s' % (spelling, short(cell))
        if spelling not in cell:
            return 'the divergence marker does not name the absent spelling `%s`' % spelling
        return None
    if exp == 'divergent':
        if not DIVERGENT.match(cell):
            return 'expected a divergence marker, found %s' % short(cell)
        return None
    if exp.startswith('nontoken:'):
        want = exp[len('nontoken:'):]
        if cell != want:
            return 'expected the documented non-token shape %s, found %s' % (short(want), short(cell))
        return None
    if exp.startswith('alias:'):
        want = exp[len('alias:'):]
        if want not in ALIASES:
            return 'its recorded alias `%s` is not in the accepted ALIASES table' % want
        if cell != '`%s`' % want:
            return 'expected the recorded alias `%s`, found %s' % (want, short(cell))
        return None
    return 'unknown recorded expectation %r' % exp


