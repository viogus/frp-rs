#!/usr/bin/env bash
# docs-go-column.sh — fixture checks for the `Go frp Equivalent` column of docs/config.md.
#
# Why this exists: docs/config.md's opening paragraph used to claim "Every field maps 1:1 to a
# Go frp v0.71.0 equivalent", but nothing measured that column. Two rows had already rotted by
# hand: PR #448 fixed a row naming a Go spelling `frps` does not accept, and PR #455 found a
# second row naming a Go field `frps` does not read. A reader who trusts the column cannot tell
# a mapped row from a divergence, and a wrong spelling is invisible to every other guard in the
# tree.
#
# What the gate measures (the four M-1 Go-column residues this round closes)
#   membership   every Go cell that names a key must appear in `GO`, the 261-spelling accept
#                set; anything else must be a recorded divergence marker or a documented
#                non-token shape.
#   the key set  `GO` is no longer trusted. `scripts/tests/docs-go-column-go-keys.txt` records
#                the same set as a derivation artifact (one spelling per line, sorted, with its
#                provenance) and the scan diffs the embedded table against it, so a
#                transcription error in either reds. The artifact is regenerated by
#                `scripts/tests/docs-go-column-derive-go-keys.sh` (`--fetch`, or `--source DIR`
#                for a local checkout); that script skips cleanly (SKIP, exit 0) when no source
#                is available, and the gate itself never needs the Go source.
#   the mapping  every data row is keyed `(table ordinal, field)` in `ROW_GO_PATHS` with the Go
#                cell it must carry — a `json` path, a qualified path plus shape, a divergence
#                marker, an extension marker naming the absent spelling, or a documented
#                non-token shape. A cell holding another real Go key (the recorded
#                falsification was `bindPort` -> `quicBindPort`) is a violation, not a pass.
#   the aliases  the 41 doc spellings the M-1 round recorded in `ALIASES` are resolved in
#                `ALIAS_RESOLUTION`: each is either repointed to the Go path it should have
#                named (checked against `GO` and against the row's recorded cell) or recorded
#                in docs/config.md as an extension whose absent spelling the marker names and
#                the recorded key set proves absent. `ALIASES` itself is now empty — no
#                accepted alias remains — but the mechanism stays, so a new one has to be
#                recorded here (and the inventory reds on an unused entry).
#
# Provenance of the recorded key set
#   Go frp v0.71.0. The annotated tag `v0.71.0` is object 40adeed73b51e7ee1766d7cfb15d02ba9431ba2b,
#   which points at commit 4a23aa181c1d7e28eecaa8216024ed753b9d27c8.
#   Source files read: pkg/config/v1/{server,client,common,proxy,visitor,proxy_plugin,
#   visitor_plugin,value_source,api,store,decode}.go.
#   `pkg/config/v1/decode.go` carries no alias or legacy table — it dispatches on the `type` key
#   straight into `jsonx.UnmarshalWithOptions` — so Go accepts only the exact `json:"..."` spellings.
#   Accept set = every dotted `json` path reachable from `ServerConfig`, `ClientConfig` and the
#   `*ProxyConfig` / `*VisitorConfig` / `*PluginOptions` structs (embedded structs followed,
#   `json:"-"` ignored), plus every bare `json` field name in the `pkg/config/v1` config structs:
#   108 dotted paths + 153 bare names = 261 distinct spellings (the two sets are disjoint).
#   Re-derive and diff the artifact:
#     bash scripts/tests/docs-go-column-derive-go-keys.sh --fetch --check
#
# A data row passes when its Go cell is
#   go         the `json` path `ROW_GO_PATHS` records for that row, and that path is in `GO`
#   qualified  `` `tok` (start|end|nested) `` with `tok` the recorded Go frp v0.71.0 spelling
#   divergent  the recorded em-dash divergence marker (`—`, `` `—` ``, optionally with prose)
#   extension  an em-dash marker naming a spelling the recorded key set proves Go does not have
#   nontoken   one of the four documented non-token shapes: `**Required.**`,
#              `` `sk` / `secretKey` ``, `` `transport.wireProtocol = "v2"` ``
#   alias      a spelling in the accepted `ALIASES` table (currently empty)
# Anything else is a violation. The `ALIASES` table is the recorded exemption for spellings a
# human has not yet resolved, and the fixture names each one's divergence in the
# failure/success message rather than hiding it.
#
# The two rows that name a Go spelling `frps` does not read are additionally pinned by line,
# field name and prose (`websocket_port` at docs/config.md:22, `tls_enable` at docs/config.md:25),
# so re-wording either back into a bare Go spelling reds even if someone later adds that spelling
# to `ALIASES` or to `GO`.
#
# The inventory counts are deliberate: a table appearing, a row being added, or a Go cell
# changing has to be recorded here in the same commit instead of passing silently.
#
# Scenarios
#   1  the row-by-row scan of `$DOCS_CONFIG` (default docs/config.md): 17 Go-column tables,
#      192 data rows, 24 divergence markers, 0 alias rows, the key-set artifact diff, the 41
#      alias resolutions, one check per data row and one per pinned row.
#   2  seven mutations of a copy of the repository's own docs/config.md, each of which must red —
#      M1 reword the `websocket_port` divergence to `websocketPort`, M2 reword `tls_enable` to
#      `tlsEnable`, M3 misspell a curated token (`bindAddr` -> `bindAddress`), M4 drop every
#      table, M5 strip the `websocket_port` divergence prose, M6 swap a real Go key into the
#      wrong row (`bindPort` -> `quicBindPort`), M7 substitute a spelling Go does not carry
#      (`bindPort` -> `kcpPort`). A green suite on any mutant would mean the fixture does not
#      drive the scan it claims to.
#
# Usage: bash scripts/tests/docs-go-column.sh
#        DOCS_CONFIG=/tmp/mutated-config.md bash scripts/tests/docs-go-column.sh
# `DOCS_CONFIG` points the scenario-1 scan at a mutated copy; the scenario-2 mutations are always
# taken from the repository's own docs/config.md, so the seam cannot switch them off.
set -uo pipefail

# --- self-defence: assert a floor on every exit path --------------------------
# A suite that silently stops checking must not exit green. The trap is installed before the path
# resolution and the first check, so an early `exit 0` anywhere below it still has to answer to the
# floor. `MIN_CHECKS` is the measured check count of a green run.
MIN_CHECKS=257
checks=0
fails=0
WORK=""

# shellcheck disable=SC2329  # invoked by the EXIT trap below, not directly
cleanup() {
  local rc=$?
  if [ -n "$WORK" ] && [ -d "$WORK" ]; then
    rm -rf "$WORK"
  fi
  if [ "$rc" -eq 0 ] && [ "$checks" -lt "$MIN_CHECKS" ]; then
    printf 'docs-go-column: only %d check(s) ran, floor %d — the suite was cut short\n' \
      "$checks" "$MIN_CHECKS" >&2
    exit 1
  fi
  exit "$rc"
}
trap cleanup EXIT

ok() {
  checks=$((checks + 1))
  printf '  ok    %s\n' "$1"
}

bad() {
  checks=$((checks + 1))
  fails=$((fails + 1))
  printf '  FAIL  %s\n' "$1"
}

# --- locate the repository even through a symlink -----------------------------
SOURCE="${BASH_SOURCE[0]}"
while [ -L "$SOURCE" ]; do
  DIR="$(cd -P "$(dirname "$SOURCE")" && pwd)"
  SOURCE="$(readlink "$SOURCE")"
  case "$SOURCE" in
    /*) ;;
    *) SOURCE="$DIR/$SOURCE" ;;
  esac
done
SCRIPT_DIR="$(cd -P "$(dirname "$SOURCE")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
PRISTINE="$REPO_ROOT/docs/config.md"

DOCS_CONFIG="${DOCS_CONFIG:-docs/config.md}"
case "$DOCS_CONFIG" in
  /*) ;;
  *) DOCS_CONFIG="$REPO_ROOT/$DOCS_CONFIG" ;;
esac

if [ ! -f "$PRISTINE" ]; then
  printf 'FAIL  cannot locate docs/config.md from %s\n' "$SCRIPT_DIR" >&2
  exit 1
fi
if [ ! -f "$DOCS_CONFIG" ]; then
  printf 'FAIL  cannot read DOCS_CONFIG=%s\n' "$DOCS_CONFIG" >&2
  exit 1
fi
if ! command -v python3 >/dev/null 2>&1; then
  printf 'FAIL  python3 not found — the Go frp equivalent column cannot be scanned\n' >&2
  exit 1
fi

WORK="$(mktemp -d)"

